"""docs/studies/results_2026/INDEX.md: every table, figure and JSON of the 2025-26 pages with its commit and config, the ranked
placeholder caveats and the thesis hand-off. Read from the pages' JSON.

    .venv/bin/python studies/results_2026_index.py
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "studies"))
DOCS = ROOT / "docs" / "studies" / "results_2026"
CONFIGS = ("configs/dbf2026_multipoint.yaml, configs/dbf2026_multipoint_rdo.yaml, configs/humpback_2026.yaml, configs/mass_usyd_loo_humpback.yaml, configs/rulesets/dbf_2025_26.yaml, configs/placeholders.yaml")


def head():
    return subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()


def page_tag(figure):
    return "compute_performance_2026.md" if figure.startswith("compute") else ("validation_2026.md" if figure.startswith(("humpback_validation", "mass_parity")) else "results_2026.md")


def main():
    R = json.loads((DOCS / "results_2026.json").read_text())
    C = json.loads((DOCS / "compute_performance_2026.json").read_text()) if (DOCS / "compute_performance_2026.json").exists() else None
    V = json.loads((DOCS / "validation_2026.json").read_text())
    L = []
    w = L.append
    w("# 2025-26 results: index\n")
    w(f"Generated by `studies/results_2026_index.py` (commit `{head()}`). Every page is generated by its script from its JSON: rerun the script rather than editing the page. **Runs:** freeze tag `results-2026-final`, commit `{R['freeze']}`, in `outputs/results_2026/` (git-ignored). The thesis' results come from this folder; the 2024-25 study (`docs/studies/results/`) is Appendix A only. The run log, decisions and cuts: `docs/development/RESULTS_LOG.md`.\n")
    w("## Pages and JSON\n\n| page | JSON | page commit | run commit | script | configs |\n|---|---|---|---|---|---|")
    w(f"| `validation_2026.md` | `validation_2026.json` | `{V.get('git')}` | `{V.get('run_git') or R['freeze']}` | `studies/validation_2026.py`, `validation_2026_report.py` | configs/humpback_2026.yaml, configs/mass_usyd_loo_humpback.yaml |")
    w(f"| `results_2026.md` | `results_2026.json` | `{R['page_git']}` | `{R['freeze']}` | `studies/results_2026.py`, `results_2026_campaign.py`, `results_2026_report.py`, `aircrafter1_2026.py` | {CONFIGS} |")
    if C:
        w(f"| `compute_performance_2026.md` | `compute_performance_2026.json` | `{C['page_git']}` | `{', '.join(C['git_runs'])}` | `studies/compute_performance_2026.py`, `compute_performance_2026_report.py` | as results_2026, reference/aircrafter1/time_2026.m |")
    w("\nAirCrafter 1.0: `outputs/results_2026/ac1/fr_ac1_2026_shipped.json`, from `reference/aircrafter1/run_2026.m` at the shipped steps (`inputs_2026.m`, `assumptions_2026.m`).\n")
    w("## Tables (`tables/*.tex` + `.csv`, the same as on the pages)\n\n| table | page | run commit |\n|---|---|---|")
    for f in sorted((DOCS / "tables").glob("*.tex")):
        w(f"| `tables/{f.name}` | {'validation_2026.md' if f.stem == 'mass_parity' else 'results_2026.md'} | `{R['freeze']}` |")
    w("\n## Figures (`figures/*.pdf` + `.png`)\n\n| figure | page | run commit |\n|---|---|---|")
    for f in sorted((DOCS / "figures").glob("*.pdf")):
        w(f"| `figures/{f.name}` | {page_tag(f.stem)} | `{R['freeze']}` |")
    w("\n## Run JSON\n\n`outputs/results_2026/runs/fr_*.json`: one per run. Monte Carlo arrays: `outputs/results_2026/mc/fr_mc_{in,out}_<design>.npz`. Timings: `outputs/results_2026/perf/`. Superseded analyses of the continuous RDO design, kept: `outputs/results_2026/superseded_continuous_rdo/` (docs/development/RESULTS_LOG.md, Decision 10).\n")
    w("## Caveats: PLACEHOLDERS ranked by their effect on F\n\nThis replaces the qualitative order of Table 3.4. Measures differ by row, as stated (the method of the 2024-25 index): a re-analysis over the plausible range at the MDO design (|dF/dp| x range, as a finite difference); a re-optimisation; or the sigma of F that a PLACEHOLDER spread gives. M2 sits in the cap's blend at the optimum, so what raises M2 barely moves capped F: the uncapped column shows it.\n\n| rank | PLACEHOLDER | effect on F | effect on uncapped F | measure |\n|---:|---|---:|---:|---|")
    for i, r in enumerate(R["ranking"], 1):
        u = r.get("effect_uncapped")
        w(f"| {i} | {r['name']} | {r['effect']:.4f} | {'–' if u is None else f'{u:.4f}'} | {r['measure']} |")
    w("\n## Thesis hand-off (RUBRIC_MAP, 'For the results prompt')\n")
    for s in hand_off(R, C, V):
        w(f"- {s}")
    w("")
    (DOCS / "INDEX.md").write_text("\n".join(L))
    print("wrote docs/studies/results_2026/INDEX.md")


def hand_off(R, C, V):
    H = []
    suite = (DOCS / "suite_counts.json")
    if suite.exists():
        s = json.loads(suite.read_text())
        H.append(f"**Test count (Table 3.3's row):** {s['freeze_passed']} passed at the freeze tag (`{R['freeze']}`, in the main checkout, the MATLAB test included); {s.get('final_passed', 'see docs/development/RESULTS_LOG.md')} at the final commit.")
    H.append(f"**The 2025-26 RDO command for Appendix C:** `AIRCRAFTER2_APC_DIR=... OMP_NUM_THREADS=3 .venv/bin/python studies/results_2026.py rdo --tag fr_rdo_mdo --case {R['best_case']} --start {R['mdo_tag']} --free` (config `configs/dbf2026_multipoint_rdo.yaml`); the rounding: `studies/results_2026.py rdo_integer --case fr_rdo_mdo`; the whole campaign: `studies/results_2026_campaign.py run`.")
    sc = R["designs"]["mdo"].get("screen")
    if sc:
        H.append(f"**Screening outcome (§3.5):** at MDO, the first-order screen over the 17-parameter list selects {', '.join(sc['selected'])} (threshold {sc['threshold']:g}, at most {sc['max_dim']}; 90 % reached for every quantity: {sc['reached']}). The RDO's set stays the settled five. f_tb on the payload-sized fuselage: sigma of F {sc['oned']['f_tb'] ** 0.5:.4f} against f_build's {sc['oned']['f_build'] ** 0.5:.4f} (results_2026.md §4).")
    rw = R.get("rewind_errors") or []
    if rw:
        H.append("**Rewind error at the AT7215 catalogue windings (§3.4.5, RESULTS_2026_PLAN §4.4):** " + "; ".join(f"{r['kv']:.0f} KV: Rm law {r['Rm_model']:.1f} against {r['Rm_cat']:.0f} mΩ ({100 * r['Rm_err']:+.1f} %), I0 law {r['I0_model']:.2f} against {r['I0_cat']:.1f} A ({100 * r['I0_err']:+.1f} %)" for r in rw) + ".")
    crit = V.get("criteria")
    if crit:
        H.append(f"**§3.7's criteria applied (§4.1):** structure within ±30 %: {crit['mass_pass']} of {crit['mass_n']} rows pass; flight performance within the report's range or 10 %: {crit['flight_pass']} of {crit['flight_n']} rows pass. validation_2026.md §0.")
    if R["ranking"]:
        H.append(f"**The PLACEHOLDER ranking (Table 3.4, §3.8):** the table above; first: {R['ranking'][0]['name']} ({R['ranking'][0]['effect']:.4f}).")
    H.append("**The calibration parity plot (§4.1, referenced from §3.4.4):** `figures/mass_parity.pdf`, data `tables/mass_parity.csv`.")
    H.append(f"**Re-check Ch3 against the freeze tag:** the thesis describes commit `73a1db4`; the tag is `{R['freeze']}`. Tables 3.1-3.2 and ch3_sources.md's line numbers need the update (`scripts/make_ch3_tables.py`); not done here, the thesis LaTeX is yours.")
    H.append("**Statement to correct:** docs/development/PLAN.md finding 2 says there's no multistart: results_2026.md §5.1 is that evidence now.")
    return H


if __name__ == "__main__":
    main()
