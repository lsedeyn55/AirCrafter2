"""Finite-difference step-size study for the NeuralFoil partials; writes docs/verification/neuralfoil_fd_steps.md.

NeuralFoil is not complex-step safe, so its partials (w.r.t. alpha, ln Re and the 18 Kulfan
parameters) are central differences. This sweeps the step size and reports the relative change
of each derivative between neighbouring steps; the chosen step should sit on the plateau.

Run: .venv/bin/python verification/neuralfoil_fd_steps.py
"""

from pathlib import Path

import numpy as np

from aircrafter2.airfoil import load_seed
from aircrafter2.airfoil.neuralfoil_section import NFSettings, nf_eval, pack

ROOT = Path(__file__).resolve().parents[1]
S = NFSettings()
STEPS = np.logspace(-1, -8, 15)


def central(P, alpha, Re, which, j, h):
    Pp, Pm = P.copy(), P.copy()
    ap = am = alpha
    Rp = Rm = Re
    if which == "alpha":
        ap, am = alpha + h, alpha - h
    elif which == "logre":
        Rp, Rm = Re * np.exp(h), Re * np.exp(-h)
    else:
        Pp[j] += h
        Pm[j] -= h
    fp = nf_eval(Pp, ap, Rp, S)
    fm = nf_eval(Pm, am, Rm, S)
    return np.array([(fp[k] - fm[k])[0] / (2 * h) for k in ("CL", "CD", "CM")])


def study(name, alpha, Re):
    s = load_seed(name)
    P = pack(s["upper_weights"], s["lower_weights"], s["leading_edge_weight"], s["TE_thickness"])
    a, r = np.array([alpha]), np.array([Re])
    dirs = [("alpha", None, "alpha [deg]"), ("logre", None, "ln Re")]
    dirs += [("k", j, f"upper w{j}") for j in (0, 3, 7)] + [("k", 8 + j, f"lower w{j}") for j in (0, 3, 7)]
    dirs += [("k", 16, "LE weight"), ("k", 17, "TE thickness")]
    rows = []
    for which, j, label in dirs:
        vals = np.array([central(P, a, r, which, j, h) for h in STEPS])  # (nsteps, 3)
        scale = np.maximum(np.abs(vals).max(axis=0), 1e-12)
        change = np.abs(np.diff(vals, axis=0)) / scale  # between neighbouring steps
        rows.append((label, change.max(axis=1)))
    return rows


def main():
    lines = ["# NeuralFoil finite-difference step study\n",
             "Generated by `verification/neuralfoil_fd_steps.py`. Each entry is the largest relative change of",
             "(dCl, dCd, dCm)/d(direction) between neighbouring step sizes (scaled by the derivative's",
             "magnitude). Small values mean a plateau. Central differences, NeuralFoil "
             f"`{S.model_size}`.\n"]
    for name, alpha, Re in [("naca4412", 3.0, 2.5e5), ("e423", 5.0, 1.5e5)]:
        rows = study(name, alpha, Re)
        lines.append(f"## {name}, alpha = {alpha} deg, Re = {Re:.2g}\n")
        hdr = " | ".join(f"{h:.0e}" for h in STEPS[1:])
        lines.append(f"| direction | {hdr} |")
        lines.append("|---|" + "---:|" * (len(STEPS) - 1))
        for label, ch in rows:
            lines.append(f"| {label} | " + " | ".join(f"{c:.0e}" for c in ch) + " |")
        lines.append("")
    lines.append("## Chosen steps (NFSettings defaults)\n")
    lines.append(f"- alpha: {S.h_alpha} deg; ln Re: {S.h_logre}; Kulfan parameters: {S.h_k} (absolute).")
    out = ROOT / "docs" / "verification" / "neuralfoil_fd_steps.md"
    out.write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
