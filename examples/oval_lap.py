"""Step 4: oval lap-time optimisation, with and without a turn power limit.

Writes docs/steps/step4_oval.md. Run: .venv/bin/python examples/oval_lap.py
"""

import time
from pathlib import Path

import numpy as np

from aircrafter2.config import load_yaml
from aircrafter2.problems.oval_lap import OvalLapProblemConfig, build_oval_lap_problem

ROOT = Path(__file__).resolve().parents[1]
ROWS = [
    ("b", "m"), ("c", "m"), ("S", "m^2"), ("tc_scale", "-"), ("camber_scale", "-"), ("tc_max", "-"),
    ("alpha_cruise", "deg"), ("alpha_turn", "deg"), ("cruise.vlm.wing_perf.CL", "-"),
    ("turn.vlm.wing_perf.CL", "-"), ("turn.CL_max", "-"), ("turn.CL_max_over_CL", "-"),
    ("n", "-"), ("turn_radius", "m"), ("lap_time", "s"), ("P_turn", "W"), ("cruise.L_over_D", "-"),
    ("turn.nf_confidence_min", "-"),
]


def run(cfg):
    prob = build_oval_lap_problem(cfg)
    prob.driver.options["disp"] = False
    t = time.perf_counter()
    res = prob.run_driver()
    return prob, res, time.perf_counter() - t


def main():
    base = load_yaml(ROOT / "configs" / "step4_oval_lap.yaml")
    cases = {"no power limit": dict(base), "P_turn <= 400 W": dict(base, power_available=400.0)}
    results = {}
    for label, data in cases.items():
        cfg = OvalLapProblemConfig(**data)
        results[label] = (cfg, *run(cfg))

    L = ["# Step 4: oval lap time at fixed speed\n",
         "Generated by `examples/oval_lap.py` from `configs/step4_oval_lap.yaml`.\n",
         "Two 1000 ft straights and two level 180-degree turns at V = 20 m/s, fixed weight 49 N.",
         "R = V^2/(g sqrt(n^2 - 1)), with n = L_turn/W from a second aero point whose C_L is limited",
         "by C_L,max/C_L >= 1.21. Lap time = (2 L_s + 2 pi R)/V.\n",
         "| Quantity | unit | " + " | ".join(results) + " |",
         "|---|---|" + "---:|" * len(results)]
    for name, unit in ROWS:
        vals = [f"{float(np.ravel(r[1].get_val(name))[0]):.4f}" for r in results.values()]
        L.append(f"| {name} | {unit} | " + " | ".join(vals) + " |")
    L.append("| converged / iterations / time | | " + " | ".join(
        f"{r[2].success} / {r[2].iter_count} / {r[3]:.1f} s" for r in results.values()) + " |")
    L += ["",
          "Reading the results:",
          "- **No power limit.** At fixed speed only the turn radius matters, so the optimiser buys lift:",
          "  maximum wing area, a thick, highly cambered section (camber_scale at its bound), and the turn",
          "  C_L margin active. Drag is irrelevant here, which is why this case is not a realistic design.",
          "- **With a 400 W turn-power placeholder,** drag comes back into the problem. The wing shrinks, t/c",
          "  returns to the spar floor, and the power constraint (not the C_L margin) sets the radius.",
          "- Step 6 replaces this oval with the full lap modeller. Steps 5 and 7 replace the fixed weight",
          "  and the power placeholder with the coupled mass and propulsion models."]
    out = ROOT / "docs" / "steps" / "step4_oval.md"
    out.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
