"""Reproduce Garcia & Gamboa (2022) Table 15 and write docs/verification/mass.md.

Run from the AirCrafter2 folder:
    .venv/bin/python examples/mass_verification.py
"""

from pathlib import Path

from aircrafter2.config import MassVerificationCase, load_yaml
from aircrafter2.mass.garcia_gamboa import build_mass_problem, mass_breakdown

ROOT = Path(__file__).resolve().parents[1]
CASES = ["ubi11", "gra13", "ubi15"]
COMPONENTS = ["m_wing", "m_ht", "m_vt", "m_tb", "m_cb", "m_gear", "m_empty", "m_total"]
LABELS = {"m_wing": "wing", "m_ht": "horizontal tail", "m_vt": "vertical tail", "m_tb": "tail boom",
          "m_cb": "cargo bay", "m_gear": "landing gear", "m_empty": "empty", "m_total": "total"}


def load(name):
    return MassVerificationCase(**load_yaml(ROOT / "configs" / "verification" / f"{name}.yaml"))


def run(case, options=None, inputs=None):
    case = case.model_copy(deep=True)
    for k, v in (options or {}).items():
        setattr(case.options, k, v)
    case.inputs.update(inputs or {})
    prob = build_mass_problem(case)
    prob.run_model()
    out = mass_breakdown(prob)
    out["t_tube_mm"] = 1e3 * float(prob.get_val("t_tube")[0])
    return out


def err(got, exp):
    return 100.0 * (got / exp - 1.0)


def main():
    cases = {n: load(n) for n in CASES}
    base = {n: run(c) for n, c in cases.items()}
    lines = []
    w = lines.append

    w("# Mass model verification: Garcia & Gamboa (2022) Table 15\n")
    w("Generated by `examples/mass_verification.py`; do not edit by hand.\n")
    w("This is a *code verification*: it checks the implementation against the paper's own calculated")
    w("masses for the three circular tube spar aircraft, using the paper's inputs (Tables 3, 12, 13, 14).")
    w("It is not a validation of the model against USYD aircraft.\n")

    w("## 1. Reproduction (default verification settings)\n")
    w("| Component | " + " | ".join(f"{cases[n].name} paper | ours | err %" for n in CASES) + " |")
    w("|---|" + "---:|---:|---:|" * len(CASES))
    for comp in COMPONENTS:
        row = [LABELS[comp]]
        for n in CASES:
            exp, got = cases[n].expected[comp], base[n][comp]
            row += [f"{exp:.3f}", f"{got:.3f}", f"{err(got, exp):+.1f}"]
        w("| " + " | ".join(row) + " |")
    worst = max(abs(err(base[n][c], cases[n].expected[c])) for n in CASES for c in COMPONENTS)
    w(f"\nLargest component error: **{worst:.1f} %**.\n")

    w("## 2. Which readings of the paper are needed\n")
    w("Three readings were needed to reproduce Table 15. Each is a switch, not a tuned factor:\n")
    w("- **Tail-boom load (`tail_boom_load_mode`).** `paper` evaluates Eq. 55 with K_ht taken")
    w("  literally from Eq. 5, K_ht = (l_ht/c)·A, so the boom shear is q|Cm|c³/l_ht: Eq. 54 divided by")
    w("  the aspect ratio. `eq54` is the self-consistent moment balance, Q = q|Cm|bc²/l_ht and M = Q·l_tb.")
    w("- **Spar sizing radius (`sizing_radius_mode`).** `paper` uses K_tube = r/c̄ (Eq. 15, with c the mean")
    w("  chord as §2.2.2 defines it) times the sizing chord c_root (§3.3), i.e. an effective radius")
    w("  r·c_root/c̄. `physical` uses r. The two are identical for a rectangular wing.")
    w("- **UBI11's general factors.** Table 15's UBI11 column was computed with UBI11's *individual*")
    w("  f_ht, f_vt, f_cb and f_gear from Table 14. The combined f_wing and f_tb are used as for the")
    w("  other aircraft (see `configs/verification/ubi11.yaml`).\n")
    variants = {
        "literal (eq54 + physical)": {"tail_boom_load_mode": "eq54", "sizing_radius_mode": "physical"},
        "boom reading only": {"tail_boom_load_mode": "paper", "sizing_radius_mode": "physical"},
        "radius reading only": {"tail_boom_load_mode": "eq54", "sizing_radius_mode": "paper"},
        "both (default)": {},
    }
    w("| Variant | " + " | ".join(f"{cases[n].name} wing / boom / empty err %" for n in CASES) + " |")
    w("|---|" + "---|" * len(CASES))
    for label, opts in variants.items():
        row = [label]
        for n in CASES:
            r = run(cases[n], opts)
            e = cases[n].expected
            row.append(f"{err(r['m_wing'], e['m_wing']):+.1f} / {err(r['m_tb'], e['m_tb']):+.0f} / "
                       f"{err(r['m_empty'], e['m_empty']):+.1f}")
        w("| " + " | ".join(row) + " |")
    w("")

    w("## 3. Sensitivity to inputs the paper does not give\n")
    w("Wing-mass change (%) relative to the default verification run.\n")
    sens = {
        "y1 = 0 (instead of b/(2 n_panels))": lambda c: {"y1": 0.0},
        "y1 = b/n_panels": lambda c: {"y1": c.inputs["b"] / c.options.n_panels},
        "x_gd = 0.25 (hold at quarter chord)": lambda c: {"x_gd": 0.25},
        "c_rib/c = 0.6": lambda c: {"c_rib_frac": 0.6},
        "c_rib/c = 0.8": lambda c: {"c_rib_frac": 0.8},
    }
    w("| Change | " + " | ".join(cases[n].name for n in CASES) + " |")
    w("|---|" + "---:|" * len(CASES))
    for label, fn in sens.items():
        row = [label]
        for n in CASES:
            r = run(cases[n], inputs=fn(cases[n]))
            row.append(f"{err(r['m_wing'], base[n]['m_wing']):+.2f}")
        w("| " + " | ".join(row) + " |")
    w("")

    w("## 4. Effect of the corrections flagged in PLAN §7\n")
    w("Wing-mass change (%) relative to the default verification run. The defaults stay as printed,")
    w("because the Table 14 factors were calibrated with them.\n")
    corr = {
        "deflection_mode = exact (G10)": {"deflection_mode": "exact"},
        "torsion_stiffness_mode = bredt (G12)": {"torsion_stiffness_mode": "bredt"},
    }
    w("| Option | " + " | ".join(cases[n].name for n in CASES) + " |")
    w("|---|" + "---:|" * len(CASES))
    for label, opts in corr.items():
        row = [label]
        for n in CASES:
            r = run(cases[n], opts)
            row.append(f"{err(r['m_wing'], base[n]['m_wing']):+.2f}")
        w("| " + " | ".join(row) + " |")
    w("")

    out = ROOT / "docs" / "verification" / "mass.md"
    out.write_text("\n".join(lines))
    print("\n".join(lines))
    print(f"\nwritten to {out}")


if __name__ == "__main__":
    main()
