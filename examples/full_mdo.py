"""Full optimisation (outer enumeration of n_motors x prop, D4/D8), then the robustness suite on the
best design.

Writes docs/problems/full_mdo.md. Run: .venv/bin/python examples/full_mdo.py [prop ...]
Layouts: AIRCRAFTER_LAYOUTS="1 2" (default both; 1 = configs/full_mdo.yaml, 2 = configs/full_mdo_twin.yaml).
"""

import os
import sys
import time
from pathlib import Path

import numpy as np

from aircrafter2.problems.full_mdo import build_full_problem, check_fixed_limits, load_full_config
from aircrafter2.robustness.suite import monte_carlo, sensitivities, worst_cases
from aircrafter2.robustness.uncertainty import load_uncertainty, resolve

ROOT = Path(__file__).resolve().parents[1]
PROPS = sys.argv[1:] or ["10x7E", "11x7E", "12x8E"]
LAYOUTS = [int(n) for n in os.environ.get("AIRCRAFTER_LAYOUTS", "1 2").split()]
CFG = {1: "full_mdo.yaml", 2: "full_mdo_twin.yaml"}
REPORT = ["b", "c", "tc_max", "camber_scale", "capacity", "l_ht", "S_ht", "S_vt", "x_batt", "x_cb_frac", "v",
          "m_total", "m_empty", "m_wing", "m_tb", "m_sys", "m_batt", "m_motor_group", "E_nom_total", "cruise.L_over_D", "CD_extra", "T_static",
          "thrust_margin_static", "I_static", "rpm_max", "energy_margin", "stall_margin", "turn_speed_margin",
          "Lap1time", "ThreeLapTime", "laps_frac", "Preq", "SM", "V_h", "V_v", "wall_ratio", "r_tube",
          "cruise.nf_confidence_min", "turn.n_stalled"]
CHECK = ["ThreeLapTime", "energy_margin", "thrust_margin_static", "stall_margin", "turn_speed_margin", "SM",
         "m_total", "laps_frac"]


def v(p, k):
    return float(np.ravel(p.get_val(k))[0])


def main():
    L = []
    w = L.append
    w("# Full AirCrafter 2.0 optimisation and robustness\n")
    w("Generated by `examples/full_mdo.py` from `configs/full_mdo.yaml` (1 motor) and")
    w("`configs/full_mdo_twin.yaml` (2 wing motors, D8). Decision B: the powertrain")
    w("(APC prop + motor + battery at full throttle) sets the power; the cruise speed is where T = D. All")
    w("motor, battery, tail and station values are PLACEHOLDERS (docs/OPEN_QUESTIONS.md Q7-Q9, Q19).\n")
    w("Objective: placeholder ThreeLapTime (year-specific scoring comes later).\n")

    runs = {}
    for n, prop in [(n, p) for n in LAYOUTS for p in PROPS]:
        cfg = load_full_config(ROOT / "configs" / CFG[n])
        cfg.propulsion.prop = prop
        prob = build_full_problem(cfg)
        prob.driver.options["disp"] = False
        t = time.perf_counter()
        try:
            res = prob.run_driver()
            ok, its = res.success, res.iter_count
        except Exception as exc:  # an MDA failure inside the optimiser
            ok, its = False, f"error: {exc.__class__.__name__}"
        runs[f"{n} x {prop}"] = dict(prob=prob, ok=ok, its=its, time=time.perf_counter() - t, n=n,
                                     limits=check_fixed_limits(prob))
        print(n, prop, ok, its, v(prob, "ThreeLapTime"), flush=True)

    w("## 1. Optimum per layout and propeller (outer enumeration, D4 / D8)\n")
    w("| Quantity | " + " | ".join(runs) + " |")
    w("|---|" + "---:|" * len(runs))
    for k in REPORT:
        w(f"| {k} | " + " | ".join(f"{v(r['prob'], k):.4g}" for r in runs.values()) + " |")
    w("| converged / iterations / time | " + " | ".join(
        f"{r['ok']} / {r['its']} / {r['time']:.0f} s" for r in runs.values()) + " |")
    w("| current & RPM limits (post-check) | " + " | ".join(
        f"{'ok' if r['limits']['ok'] else 'VIOLATED'} ({r['limits']['I_margin_A']:+.0f} A, "
        f"{r['limits']['rpm_margin']:+.0f} rpm)" for r in runs.values()) + " |")
    feasible = {p: r for p, r in runs.items() if r["ok"] and r["limits"]["ok"]}
    for n in LAYOUTS:
        fl = {p: r for p, r in feasible.items() if r["n"] == n}
        bn = min(fl, key=lambda p: v(fl[p]["prob"], "ThreeLapTime")) if fl else None
        w(f"\nBest feasible, {n} motor(s): " + (f"**{bn}** ({v(fl[bn]['prob'], 'ThreeLapTime'):.2f} s)." if bn
                                                else "none."))
    best = min(feasible, key=lambda p: v(feasible[p]["prob"], "ThreeLapTime")) if feasible else None
    w(f"\nBest feasible overall: **{best}** (robustness below). Layouts at equal prop have unequal installed power "
      "with the placeholder unit: see docs/studies/twin_motor_study.md.\n" if best else "\nNo feasible design.\n")
    if not best:
        (ROOT / "docs" / "problems" / "full_mdo.md").write_text("\n".join(L))
        return

    prob = runs[best]["prob"]
    w("## 2. Sensitivities of the 3-lap time at the best design\n")
    w("Normalised: (x / t) dt/dx, i.e. % change of the 3-lap time per % change of x.\n")
    dvs = list(load_full_config(ROOT / "configs" / CFG[runs[best]["n"]]).design_variables)
    assumptions = ["m_pay", "f_tb", "f_cb", "f_gear", "f_ht", "f_vt", "e_spec", "R_cell", "Kv", "Rm", "m_avionics",
                   "m_motor", "eta_h", "rho"]
    sens = sensitivities(prob, "ThreeLapTime", dvs + assumptions)
    w("| Variable | kind | sensitivity |")
    w("|---|---|---:|")
    for k, s in sorted(sens.items(), key=lambda kv: -abs(kv[1])):
        w(f"| {k} | {'design variable' if k in dvs else 'assumption'} | {s:+.4f} |")
    w("\nAt a constrained optimum the design-variable sensitivities are not zero: they are balanced by")
    w("the active constraints (Lagrange multipliers). The assumption sensitivities say which placeholder")
    w("values matter most and should be replaced with USYD data first.\n")

    w("## 3. Worst cases (one at a time, full MDA re-analysis, design held fixed)\n")
    wc = worst_cases(prob, CHECK)
    w("| Case | " + " | ".join(CHECK) + " |")
    w("|---|" + "---:|" * len(CHECK))
    for case, vals in wc.items():
        w(f"| {case} | " + " | ".join(f"{vals[k]:.4g}" for k in CHECK) + " |")
    w("\nNegative energy_margin means the battery no longer covers three laps; the 3-lap optimum sizes")
    w("the battery to exactly three laps, so it has no energy reserve by construction. A real mission")
    w("objective (or an explicit reserve constraint) is needed before the battery size means anything.\n")

    w("## 4. Monte Carlo on the best design (n = 40, independent)\n")
    # one source for the spreads: configs/uncertainty.yaml (also used by robust design optimisation)
    dists = resolve(load_uncertainty(ROOT / "configs" / "uncertainty.yaml"), lambda name: v(prob, name))
    w("Distributions (configs/uncertainty.yaml, PLACEHOLDERS, OPEN_QUESTIONS Q32): " + ", ".join(
        f"{d.name} {d.kind} {d.mean:.4g} +/- {d.scale:.3g}" for d in dists))
    w("")
    mc = monte_carlo(prob, dists, CHECK, n=40)
    S = mc["samples"]
    w(f"Failed analyses: {mc['failed']} of 40.\n")
    w("| Output | mean | std | min | max |")
    w("|---|---:|---:|---:|---:|")
    for i, k in enumerate(mc["names"]):
        col = S[:, i]
        w(f"| {k} | {col.mean():.4g} | {col.std():.3g} | {col.min():.4g} | {col.max():.4g} |")
    cfg = load_full_config(ROOT / "configs" / "full_mdo.yaml")
    st = cfg.stability
    idx = {k: i for i, k in enumerate(mc["names"])}
    viol = {
        "energy for 3 laps": np.mean(S[:, idx["energy_margin"]] < 0),
        "take-off static thrust": np.mean(S[:, idx["thrust_margin_static"]] < 0),
        "1.2 V_stall": np.mean(S[:, idx["stall_margin"]] < 0),
        f"static margin in [{st.SM_min}, {st.SM_max}]": np.mean((S[:, idx["SM"]] < st.SM_min) | (S[:, idx["SM"]] > st.SM_max)),
    }
    w("\n| Constraint | P(violated) |")
    w("|---|---:|")
    for k, pv in viol.items():
        w(f"| {k} | {pv:.2f} |")
    w("\nConstraints active at the optimum (energy, static margin) are violated in a large share of the samples:")
    w("an optimum sits on its active constraints. Conservative margins (e.g. an energy reserve, a static")
    w("margin target inside the band) are the pragmatic fix; the robust variant can be added to the config.")

    (ROOT / "docs" / "problems" / "full_mdo.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
