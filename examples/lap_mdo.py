"""Lap modeller checks and the coupled lap-time optimisation; writes docs/problems/lap_mdo.md.

Run: .venv/bin/python examples/lap_mdo.py
"""

import csv
import time
from pathlib import Path

import numpy as np
import openmdao.api as om

from aircrafter2.mission.lap_modeller import DEFAULT_ASSUMPTIONS as A
from aircrafter2.mission.lap_modeller import isa_density, performance_modeller
from aircrafter2.mission.smooth_lap import SmoothLapModel
from aircrafter2.problems.lap_mdo import build_lap_mdo_problem, load_lap_mdo_config

ROOT = Path(__file__).resolve().parents[1]
MATLAB_CSV = ROOT / "tests" / "data" / "matlab_reference.csv"
GRID = [(5, 1.2, 6, 20), (7, 1.5, 9, 25), (4, 1.5, 6, 18), (6, 1.0, 5, 28), (5, 1.5, 8, 15), (3, 1.0, 5, 22),
        (6, 1.4, 7, 24), (3.5, 1.2, 6, 16)]


def design(m, b, AR, V, bf=1.0):
    return dict(m=m, b=b, AR=AR, V=V, altitude=400.0, takeoff_distance=100.0, mission_time=300.0,
                battery_fraction=bf)


def v(p, k):
    return float(np.ravel(p.get_val(k))[0])


def main():
    L = []
    w = L.append
    w("# The AirCrafter lap modeller, checked and coupled\n")
    w("Generated by `examples/lap_mdo.py`.\n")

    # 1. MATLAB
    w("## 1. Code check: Python port vs the original MATLAB\n")
    if MATLAB_CSV.exists():
        rows = list(csv.DictReader(open(MATLAB_CSV)))
        w("Port with `matlab_compat=True` vs `performance_modeller.m` (unchanged), "
          "`tests/data/matlab_reference.csv`.\n")
        w("MATLAB R2026a, run with `verification/matlab/run_reference.m`.\n")
        w("| m | b | AR | V | battery fraction | MATLAB 3-lap (s) | port 3-lap (s) | max rel. diff (Lap1, other, 3-lap, Preq, Tstatic) | laps M/P |")
        w("|---:|---:|---:|---:|---:|---:|---:|---:|---|")
        for r in rows:
            d = design(float(r["m"]), float(r["b"]), float(r["AR"]), float(r["V"]), float(r["batteryFraction"]))
            py = performance_modeller(A, d, matlab_compat=True)
            pre = f"| {r['m']} | {r['b']} | {r['AR']} | {r['V']} | {r['batteryFraction']} |"
            if r["NaNflag"] == "1":
                w(pre + f" NaN (screened) | stall margin {py['stall_margin']:+.2f} m/s | - | - |")
                continue
            if np.isnan(float(r["ThreeLapTime"])):
                w(pre + f" NaN (unflagged, M7) | {py['ThreeLapTime']} | NaN in both | "
                  f"{int(float(r['lapCount']))}/{py['lapCount']} |")
                continue
            diffs = [abs(py[k] / float(r[k]) - 1) for k in ["Lap1time", "otherLapTime", "ThreeLapTime", "Preq", "Tstatic"]]
            w(pre + f" {float(r['ThreeLapTime']):.3f} | {py['ThreeLapTime']:.3f} | {max(diffs):.1e} | "
              f"{int(float(r['lapCount']))}/{py['lapCount']} |")
    else:
        w("**Pending.** MATLAB could not be started headless from this session (it waits for a MathWorks")
        w("sign-in). Run `matlab -batch \"run('verification/matlab/run_reference.m')\"` from `AirCrafter2/`;")
        w("it writes `tests/data/matlab_reference.csv`, and `tests/test_lap_modeller.py` then compares the")
        w("port (with `matlab_compat=True`) against it automatically. Then rerun this script.")
    if MATLAB_CSV.exists():
        w("")
        w("The port reproduces MATLAB to round-off (~1e-8) wherever MATLAB returns numbers. Lap counts")
        w("match, including the always-1 count with batteryFraction = 0 (M2). The checks found one more")
        w("MATLAB bug (M7): at m = 7, b = 1.5, AR = 9, V = 25 the aircraft enters the first turn at")
        w("20.00 m/s, below the deceleration table's range (20.32 m/s, where turning at C_L,max stops")
        w("slowing it down). MATLAB's interp1 returns NaN outside a table and nothing flags it, so the lap")
        w("times are NaN and the count is 1. `matlab_compat` reproduces this. The default port now keeps")
        w("the speed unchanged there (the old port clamped to the table edge and sped the aircraft up).")
    w("")

    # 2. twin
    w("## 2. Smooth twin (D2) vs the reference port\n")
    w("Static AirCrafter 1.0 assumptions (Cd0 0.012, e 0.85, Clmax 1.4, eta 0.7, n 5), Wichita 400 m.\n")
    w("| m | b | AR | V | ref 3-lap (s) | twin 3-lap (s) | diff | ref Lap1 | twin Lap1 | laps ref/twin | twin time |")
    w("|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|")
    p = om.Problem(reports=False)
    p.model.add_subsystem("lap", SmoothLapModel(), promotes=["*"])
    p.setup()
    for pt in GRID:
        m, b, AR, V = pt
        ref = performance_modeller(A, design(*pt))
        for k, val in dict(m=m, S=b * b / AR, V=V, rho=isa_density(400.0), CD0=A["Cd0"], CD1=0.0,
                           k=1 / (np.pi * AR * A["e"]), CL_max=A["Clmax"], CL_to=A["Clto"], eta=A["eta"],
                           n_struct=A["n"], mu_roll=A["mu"], E_avail=A["E"], g=9.81).items():
            p.set_val(k, val)
        t = time.perf_counter()
        p.run_model()
        dt = time.perf_counter() - t
        w(f"| {m} | {b} | {AR} | {V} | {ref['ThreeLapTime']:.2f} | {v(p, 'ThreeLapTime'):.2f} | "
          f"{100 * (v(p, 'ThreeLapTime') / ref['ThreeLapTime'] - 1):+.2f} % | {ref['Lap1time']:.2f} | "
          f"{v(p, 'Lap1time'):.2f} | {ref['lapCount']}/{v(p, 'lapCount'):.0f} | {1e3 * dt:.0f} ms |")
    w("\nPreq, Tstatic and the stall margin agree to machine precision (same closed forms).")
    w("The twin's straights are RK4 in distance and its turns RK4 in time, so it has no lookup tables,")
    w("no while loops and exact complex-step partials. The remaining differences (<= 1 % on the 3-lap")
    w("time) come from the reference's Euler tables (dt = 0.1 s).\n")

    # 3. coupled
    cfg = load_lap_mdo_config(ROOT / "configs" / "lap_mdo.yaml")
    prob = build_lap_mdo_problem(cfg)
    prob.driver.options["disp"] = False
    prob.run_model()
    keys = ["b", "c", "tc_max", "camber_scale", "v", "m_total", "CD0", "CD1", "k", "cruise.CL_max",
            "cruise.L_over_D", "Vstall", "stall_margin", "turn_speed_margin", "Preq", "Tstatic", "Lap1time",
            "otherLapTime", "ThreeLapTime", "laps_frac", "lapCount", "energy_3laps", "wall_ratio", "r_tube"]
    base = {k: v(prob, k) for k in keys}
    t = time.perf_counter()
    res = prob.run_driver()
    dt = time.perf_counter() - t
    w("## 3. Coupled lap model: minimise the 3-lap time\n")
    w("`configs/lap_mdo.yaml`. Mass from the G&G closure, polar CD = CD0 + CD1 CL + k CL^2")
    w("through three coupled aero points (cruise, mid, 0.95 C_L,max), C_L,max by the critical-section")
    w("method. DVs: b, c, tc_scale, camber_scale, V. Electrical power <= 300 W is a PLACEHOLDER here")
    w("(no propulsion model; full_mdo adds one).\n")
    w(f"Converged: **{res.success}**, {res.iter_count} iterations, {dt:.0f} s.\n")
    w("| Quantity | start | optimum |")
    w("|---|---:|---:|")
    for k in keys:
        w(f"| {k} | {base[k]:.4g} | {v(prob, k):.4g} |")
    w("")
    w("Reading the optimum:")
    w("- V goes to its 30 m/s bound and electrical power to the 300 W placeholder.")
    w("- **Finding L1: the constant-power assumption rewards cruise drag.** AirCrafter sets the power")
    w("  as P = D(V) V / eta (Kallarackel Eq. 3.4): the throttle that holds V in level flight. A draggier")
    w("  aircraft therefore flies the whole lap at a higher power, with more thrust to accelerate out of")
    w("  the turns. The optimiser exploits this: maximum camber (C_L,max up, tighter stall-limited turns)")
    w("  *and* a cruise L/D of ~4, because the extra drag buys power, up to the 300 W cap. A grid search")
    w("  over static Cd0 and e (AirCrafter 1.0) cannot see this; coupled gradients do.")
    w("  Proposed fix (adopted in full_mdo): the power setting comes from the propulsion model (throttle or")
    w("  available power), not from the cruise drag; V is then the speed that power sustains.")
    w("- A two-point polar (CD0 + k CL^2 through cruise and one high-C_L point) was tried first and gave")
    w("  k < 0 at this kind of design (a highly cambered section at low cruise C_L is off its drag")
    w("  bucket), i.e. an unphysical polar extrapolated to C_L,max. The three-point polar interpolates")
    w("  over the whole C_L range the lap model uses and stays convex (k > 0). The lap time is similar")
    w("  either way, because the V bound and the power cap set it.")
    out = ROOT / "docs" / "problems" / "lap_mdo.md"
    out.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
