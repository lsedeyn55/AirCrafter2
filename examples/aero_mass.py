"""Step 5: coupled aero + mass. MDA convergence grid, t/c trade sweep, optimisation.

Writes docs/steps/step5_aero_mass.md. Run: .venv/bin/python examples/aero_mass.py
"""

import itertools
import time
from pathlib import Path

import numpy as np

from aircrafter2.problems.aero_mass import build_aero_mass_problem, load_aero_mass_config

ROOT = Path(__file__).resolve().parents[1]
CFG = ROOT / "configs" / "aero_mass.yaml"


def cfg_with(gauge):
    cfg = load_aero_mass_config(CFG)
    cfg.mass.options.use_min_gauge = gauge
    return cfg


def v(p, k):
    return float(np.ravel(p.get_val(k))[0])


def main():
    L = []
    w = L.append
    w("# Step 5: coupled aero + mass (MDF)\n")
    w("Generated by `examples/aero_mass.py` from `configs/aero_mass.yaml` (placeholder aircraft:")
    w("rectangular wing, NACA 4412 seed, V = 20 m/s, n = 5, m_pay = 1.5 kg, m_sys = 1.2 kg).\n")
    w("MDA: Newton (solve_subsystems) + DirectSolver over {cruise aero point, lift balance alpha:")
    w("L = W, G&G mass group with its own NLBGS closure}. Couplings: W -> lift balance; C_m,wing and")
    w("C_L,alpha -> loads (Eqs. 46, 47, 54); t/c, t at spar, A/c^2, P/c -> mass; tube radius from the")
    w("section thickness (D1).\n")

    # 1. convergence over the DV box
    cfg = cfg_with(True)
    prob = build_aero_mass_problem(cfg, driver=False)
    w("## 1. MDA convergence over the design-variable bounds\n")
    w("| b | c | tc_scale | camber_scale | Newton its | time (s) | m_total (kg) | alpha (deg) | t_tube (mm) |")
    w("|---:|---:|---:|---:|---:|---:|---:|---:|---:|")
    names = list(cfg.design_variables)
    pts = [tuple(cfg.design_variables[n].upper if k else cfg.design_variables[n].lower for n, k in zip(names, c))
           for c in itertools.product([0, 1], repeat=4)]
    pts.append(tuple(0.5 * (cfg.design_variables[n].lower + cfg.design_variables[n].upper) for n in names))
    worst = 0
    for pt in pts:
        for n, val in zip(names, pt):
            prob.set_val(n, val)
        t = time.perf_counter()
        prob.run_model()
        its = prob.model.mda.nonlinear_solver._iter_count
        worst = max(worst, its)
        w(f"| {pt[0]:.2f} | {pt[1]:.2f} | {pt[2]:.2f} | {pt[3]:.2f} | {its} | {time.perf_counter() - t:.1f} | "
          f"{v(prob, 'm_total'):.3f} | {v(prob, 'alpha_cruise'):.2f} | {1e3 * v(prob, 't_tube'):.3f} |")
    w(f"\nAll {len(pts)} points converged (atol 1e-10); worst case {worst} Newton iterations.")
    w("Convergence is not feasibility: e.g. at b = 1.52, c = 0.15, t/c = 0.06 the derived tube is so small")
    w("that strength needs a wall thicker than its radius. The equations still solve; the optimisation's")
    w("wall-ratio and minimum-radius constraints are what exclude such designs.\n")

    # 2. t/c sweep
    w("## 2. The t/c trade (b = 1.2 m, c = 0.3 m, camber_scale = 1)\n")
    for gauge in (True, False):
        p = build_aero_mass_problem(cfg_with(gauge), driver=False)
        w(f"**Spar minimum gauge {'on (0.5 mm)' if gauge else 'off'}**\n")
        w("| t/c | r_tube (mm) | t_tube (mm) | m_tube (kg) | m_wing (kg) | m_total (kg) | C_Dp | D (N) |")
        w("|---:|---:|---:|---:|---:|---:|---:|---:|")
        for ts in [0.5, 0.7, 0.9, 1.1, 1.3, 1.6]:
            p.set_val("tc_scale", ts)
            p.run_model()
            w(f"| {v(p, 'tc_max'):.3f} | {1e3 * v(p, 'r_tube'):.2f} | {1e3 * v(p, 't_tube'):.3f} | "
              f"{v(p, 'm_tube'):.4f} | {v(p, 'm_wing'):.4f} | {v(p, 'm_total'):.3f} | {v(p, 'cruise.CDp'):.5f} | "
              f"{v(p, 'cruise.D'):.4f} |")
        w("")
    w("- Strength-governed spar (gauge off): tube mass falls as t/c grows (t_sigma ~ 1/r^2 with")
    w("  r ~ t/c), the expected half of the trade. The G&G LE/TE stringer and rib masses scale with the")
    w("  section area, though, so the total wing mass still rises above t/c ~ 0.08.")
    w("- Gauge-governed spar (gauge on): the wall is fixed, so tube mass grows with r, i.e. with t/c.")
    w("- At this scale the drag change dominates the weight change (dD/dW ~ 2 D_i / W), so on this")
    w("  coarse grid D falls monotonically toward thin sections. What stops the thinning is the spar:")
    w("  section 3 shows the optimiser running into the tube-sizing limits.\n")

    # 3. optimisation
    w("## 3. Optimisation: minimise cruise drag (b, c, tc_scale, camber_scale; alpha from the MDA)\n")
    rows = ["b", "c", "tc_max", "camber_scale", "r_tube", "t_tube", "wall_ratio", "m_tube", "m_wing", "m_tb",
            "m_total", "cruise.vlm.wing_perf.CL", "cruise.CDp", "cruise.D", "cruise.L_over_D",
            "cruise.CL_max_over_CL", "cruise.nf_confidence_min"]
    res = {}
    for gauge in (True, False):
        p = build_aero_mass_problem(cfg_with(gauge))
        p.driver.options["disp"] = False
        t = time.perf_counter()
        r = p.run_driver()
        res[gauge] = (p, r, time.perf_counter() - t)
    w("| Quantity | spar min gauge on | spar min gauge off |")
    w("|---|---:|---:|")
    for k in rows:
        w(f"| {k} | {v(res[True][0], k):.4g} | {v(res[False][0], k):.4g} |")
    w("| converged / iterations / time | " + " | ".join(
        f"{res[g][1].success} / {res[g][1].iter_count} / {res[g][2]:.0f} s" for g in (True, False)) + " |")
    w("")
    w("Active constraints: span at its upper bound and the minimum tube radius (5 mm placeholder),")
    w("with the wall at t/r ~ 0.2. Strength needs a ~1 mm wall once the section, and with it the tube,")
    w("is that thin, so the 0.5 mm spar gauge is inactive and both columns coincide. The spar sets the")
    w("thinnest section, at t/c ~ 0.08 for this aircraft. That is the drag-vs-spar trade.")
    w("")
    w("Tail boom: both cases use the 1 mm minimum boom wall with the refitted f_tb = 0.847")
    w("(docs/studies/tail_boom_calibration.md); the gauge switch above affects the spar only.")
    w("")

    out = ROOT / "docs" / "steps" / "step5_aero_mass.md"
    out.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
