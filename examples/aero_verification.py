"""Step 3 checks and the step 3 optimisation; writes docs/aero_verification.md.

Run: .venv/bin/python examples/aero_verification.py
"""

import time
from pathlib import Path

import numpy as np
import openmdao.api as om

from aircrafter2.aero import WingAero
from aircrafter2.airfoil import AirfoilGroup, load_seed
from aircrafter2.atmosphere import isa
from aircrafter2.config import load_yaml
from aircrafter2.problems.wing_aero import WingAeroProblemConfig, build_wing_aero_problem
from aircrafter2.verification.hand_calcs import hand_wing_drag, lifting_line_rect, trefftz_induced_drag

ROOT = Path(__file__).resolve().parents[1]
B, C, V, AIRFOIL = 1.5, 0.25, 15.0, "naca4412"


def wing_point(num_y, spacing="cosine", alpha=6.5):
    seed = load_seed(AIRFOIL)
    p = om.Problem(reports=False)
    p.model.add_subsystem("airfoil", AirfoilGroup(seed=seed), promotes=["*"])
    p.model.add_subsystem("wing", WingAero(num_x=2, num_y=num_y, spacing=spacing), promotes=["*"])
    p.setup()
    a = isa(0.0)
    for k, v in dict(b=B, c=C, v=V, rho=a["rho"], mu=a["mu"], alpha=alpha).items():
        p.set_val(k, v)
    p.run_model()
    return p, seed, a


def val(p, name):
    return float(np.ravel(p.get_val(name))[0])


def main():
    L = []
    w = L.append
    AR = B / C
    w("# Aero verification (step 3)\n")
    w("Generated by `examples/aero_verification.py`. Wing: rectangular, b = 1.5 m, c = 0.25 m (AR 6),")
    w(f"{AIRFOIL.upper()}, V = 15 m/s, sea level (Re = 2.6e5), OAS VLM aero-only + NeuralFoil strips.\n")

    # 1. hand calculation
    p, seed, a = wing_point(41)
    CL, CDi, CDp, CD = (val(p, k) for k in ["vlm.wing_perf.CL", "vlm.wing_perf.CDi", "CDp", "CD"])
    llt = lifting_line_rect(AR)
    Re = a["rho"] * V * C / a["mu"]
    hand = hand_wing_drag(seed, CL, Re, AR, llt["e"])
    G = p.get_val("vlm.circulations").reshape(1, -1)[-1]
    tz = trefftz_induced_drag(G, p.get_val("mesh.mesh")[0, :, 1], V, a["rho"], val(p, "vlm.wing.S_ref"))
    e_vlm = CL**2 / (np.pi * AR * CDi)
    w("## 1. Hand calculation\n")
    w("| Quantity | Model | Hand / independent | Difference |")
    w("|---|---:|---:|---:|")
    w(f"| C_L at alpha = 6.5 deg (from zero lift) | {CL:.4f} | {llt['CL_alpha'] * np.radians(6.5):.4f} "
      f"(lifting line) | {100 * (CL / (llt['CL_alpha'] * np.radians(6.5)) - 1):+.1f} % |")
    w(f"| C_Di, near field vs Trefftz plane | {CDi:.5f} | {tz['CDi']:.5f} (Trefftz) | "
      f"{100 * (CDi / tz['CDi'] - 1):+.2f} % |")
    w(f"| span efficiency e | {e_vlm:.4f} | {llt['e']:.4f} (lifting line) | {100 * (e_vlm / llt['e'] - 1):+.1f} % |")
    w(f"| C_Dp, strip integral vs 2D c_d(c_l = C_L) | {CDp:.5f} | {hand['cd_2d']:.5f} | "
      f"{100 * (CDp / hand['cd_2d'] - 1):+.1f} % |")
    w(f"| C_D total | {CD:.5f} | {hand['CD']:.5f} | {100 * (CD / hand['CD'] - 1):+.1f} % |")
    w("")
    w("Notes:")
    w("- The Trefftz-plane drag from OAS's own circulations matches its near-field drag, so the VLM")
    w("  force integration is self-consistent.")
    w("- VLM and lifting line differ by a few % in e and C_L,alpha at AR 6. Lifting line is the")
    w("  cruder model for a low-AR rectangular wing; the VLM has finite chord. The two errors partly")
    w("  cancel in total C_D.")
    w("- The strip C_Dp is higher than the 2D value because the tip strips fly at lower c_l, where")
    w("  NACA 4412's drag is above its minimum.")
    w("- The VLM is a flat-plate model: camber does not enter it, so its alpha is measured from zero")
    w("  lift. Strips are matched on c_l, and NeuralFoil supplies the true section alpha (`alpha_sec`).\n")

    # 2. mesh convergence
    w("## 2. Spanwise mesh convergence (num_x = 2)\n")
    w("| half-wing nodes | span efficiency e | C_L | C_D | run time (s) |")
    w("|---:|---:|---:|---:|---:|")
    for ny in [11, 21, 41, 81, 161]:
        t = time.perf_counter()
        q, _, _ = wing_point(ny)
        dt = time.perf_counter() - t
        cl, cdi = val(q, "vlm.wing_perf.CL"), val(q, "vlm.wing_perf.CDi")
        w(f"| {ny} | {cl**2 / (np.pi * AR * cdi):.4f} | {cl:.4f} | {val(q, 'CD'):.5f} | {dt:.2f} |")
    w("\nDefault: 41 nodes (40 strips per half), about 1 % from the finest mesh in e.\n")

    # 3. step 3 optimisation
    cfg = WingAeroProblemConfig(**load_yaml(ROOT / "configs" / "step3_wing_aero.yaml"))
    prob = build_wing_aero_problem(cfg)
    prob.driver.options["disp"] = False
    prob.run_model()
    init = {k: val(prob, k) for k in ["CD", "L_over_D", "lift_residual"]}
    t = time.perf_counter()
    res = prob.run_driver()
    dt = time.perf_counter() - t
    w("## 3. Step 3 optimisation: minimise C_D at fixed lift and wing area\n")
    w("Config: `configs/step3_wing_aero.yaml`. SLSQP, gradients from analytic/implicit partials.\n")
    w(f"Converged: **{res.success}** in {res.iter_count} iterations, {dt:.1f} s, from an infeasible start "
      f"(lift {100 * init['lift_residual']:+.0f} % of W). Optimum L/D = {val(prob, 'L_over_D'):.2f}.\n")
    w("| Variable | Optimum | Bound / constraint |")
    w("|---|---:|---|")
    dv = cfg.design_variables
    for k in ["b", "c", "alpha", "tc_scale", "camber_scale"]:
        v = val(prob, k)
        note = "at upper bound" if abs(v - dv[k].upper) < 1e-6 else ("at lower bound" if abs(v - dv[k].lower) < 1e-6 else "")
        w(f"| {k} | {v:.4f} | {note} |")
    for k, note in [("vlm.wing_perf.CL", "L = W"), ("vlm.wing_perf.CDi", ""), ("CDp", ""),
                    ("tc_max", f">= {cfg.tc_min}"), ("CL_max", ""),
                    ("CL_max_over_CL", f">= {cfg.clmax_ratio_min}"), ("nf_confidence_min", "report only")]:
        w(f"| {k} | {val(prob, k):.4f} | {note} |")
    w("\nThe span goes to its 5 ft bound (induced drag), t/c to the spar placeholder (profile drag),")
    w("and camber trades section drag against the required c_l. The t/c bound is where step 5's spar")
    w("mass will push back.")

    out = ROOT / "docs" / "aero_verification.md"
    out.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
