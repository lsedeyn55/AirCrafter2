"""Recalibrate the tail-boom/fuselage factor f_tb for a minimum boom wall.

G&G's f_tb = 12.81 (Table 14) multiplies a boom tube whose wall comes from the load equations
(Eqs. 119-123). For the paper's aircraft those walls are ~0.06 mm, far thinner than any real
tube. With a realistic minimum wall the tube is ~10x heavier, so f_tb must be refitted on that
basis. This refits it with the paper's own data: the *real* tail-boom masses of UBI11, GRA13 and
UBI15 (Table 15), Eq. 127 per aircraft and Eq. 128 combined.

Writes docs/studies/tail_boom_calibration.md. Run: .venv/bin/python examples/tail_boom_calibration.py
"""

from pathlib import Path

from aircrafter2.config import MassVerificationCase, load_yaml
from aircrafter2.mass.calibration import fit_correction_factors

ROOT = Path(__file__).resolve().parents[1]
REAL_TB = {"ubi11": 0.126, "gra13": 0.200, "ubi15": 0.175}  # Table 15, real/reported tail boom mass (kg)
WALLS = [0.5e-3, 1.0e-3, 1.5e-3]  # m; 1.0 mm = USYD tubes in Spar Sizer 3.1 (22/20, 20/18 mm)


def case(name, wall):
    c = MassVerificationCase(**load_yaml(ROOT / "configs" / "verification" / f"{name}.yaml"))
    c.options.tb_min_gauge = True
    c.inputs["t_tb_min"] = wall
    return c


def main():
    L = ["# Tail-boom factor f_tb recalibrated for a minimum boom wall\n",
         "Generated by `examples/tail_boom_calibration.py`.\n",
         "G&G size the boom wall from the loads (Eqs. 119-123): about 0.06 mm for their aircraft, and",
         "micrometres for a DBF-scale aircraft. f_tb = 12.81 (Table 14) was fitted to those walls, so it",
         "absorbs a factor of ~10 that a real tube wall does not need. With a minimum wall the factor is",
         "refitted here to the paper's *real* boom masses (Table 15), with the calibration hook",
         "(Eqs. 127-128, `aircrafter2/mass/calibration.py`). Other inputs: the verification configs.\n",
         "| Minimum wall | f_tb UBI11 | f_tb GRA13 | f_tb UBI15 | f_tb combined (Eq. 128) | boom-mass errors with combined f_tb |",
         "|---:|---:|---:|---:|---:|---|"]
    combined = {}
    for wall in WALLS:
        ind = {}
        for n in REAL_TB:
            r = fit_correction_factors([(case(n, wall), {"m_tb": REAL_TB[n]})], ["f_tb"],
                                       x0=[1.0], bounds={"f_tb": (0.05, 100.0)})
            ind[n] = r.factors["f_tb"]
        rc = fit_correction_factors([(case(n, wall), {"m_tb": REAL_TB[n]}) for n in REAL_TB], ["f_tb"],
                                    x0=[1.0], bounds={"f_tb": (0.05, 100.0)})
        combined[wall] = rc.factors["f_tb"]
        errs = ", ".join(f"{n.upper()} {100 * e['m_tb']:+.0f} %" for n, e in zip(REAL_TB, rc.relative_errors))
        L.append(f"| {1e3 * wall:.1f} mm | {ind['ubi11']:.3f} | {ind['gra13']:.3f} | {ind['ubi15']:.3f} | "
                 f"**{combined[wall]:.3f}** | {errs} |")
    L += ["",
          "For comparison, G&G's own combined fit (load-based walls) has boom errors of +10, -32 and +10 %",
          "(Table 15, RMS 20 %). The minimum-wall basis fits the same three booms somewhat worse",
          "(RMS ~26 %), but its wall is physically realistic and the factor is ~1 instead of ~13.",
          "",
          f"Default adopted in `configs/mass_garcia_gamboa_2022.yaml`: t_tb_min = 1.0 mm (USYD tube walls,",
          f"Spar Sizer 3.1) with f_tb = {combined[1.0e-3]:.3f}. The boom term is then essentially 'a CFRP tube of",
          "the boom's diameter and length, times ~1'. Recalibrate on USYD aircraft when data exist",
          "(OPEN_QUESTIONS Q14). The Table 15 verification keeps the paper's basis (no minimum wall,",
          "f_tb = 12.81)."]
    out = ROOT / "docs" / "studies" / "tail_boom_calibration.md"
    out.write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
